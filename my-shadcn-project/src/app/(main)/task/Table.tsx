// Create a separate component for the drag handle
function DragHandle({ id }: { id: number }) {
  const { attributes, listeners } = useSortable({
    id,
  });
  return (
    <Button
      {...attributes}
      {...listeners}
      variant="ghost"
      size="icon"
      className="text-muted-foreground size-7 hover:bg-transparent"
    >
      <IconGripVertical className="text-muted-foreground size-3" />
      <span className="sr-only">Drag to reorder</span>
    </Button>
  );
}

const getInitials = (name: string) => {
  return name
    .split(" ")
    .map((word) => word.charAt(0))
    .join("")
    .toUpperCase()
    .slice(0, 2);
};

const getStatusBadge = (status: string) => {
  const statusConfig = {
    open: { variant: "destructive" as const, label: "Open" },
    in_progress: { variant: "default" as const, label: "In Progress" },
    completed: { variant: "secondary" as const, label: "Completed" },
    closed: { variant: "outline" as const, label: "Closed" },
  };

  const config = statusConfig[status as keyof typeof statusConfig] || {
    variant: "outline" as const,
    label: status,
  };
  return <Badge variant={config.variant}>{config.label}</Badge>;
};

const renderPersonList = (
  people: Array<{ id: number; full_name: string }>,
  maxDisplay = 2
) => {
  if (!people || people.length === 0)
    return <span className="text-muted-foreground">None</span>;

  const displayPeople = people.slice(0, maxDisplay);
  const remainingCount = people.length - maxDisplay;

  return (
    <div className="flex flex-wrap gap-1">
      {displayPeople.map((person) => (
        <div
          key={person.id}
          className="flex items-center gap-1 bg-muted rounded-md px-2 py-1 text-xs"
        >
          <Avatar className="h-4 w-4">
            <AvatarFallback className="text-xs">
              {getInitials(person.full_name)}
            </AvatarFallback>
          </Avatar>
          {/* <span className="truncate max-w-20" title={person.full_name}>
            {person.full_name}
          </span> */}
        </div>
      ))}
      {remainingCount > 0 && (
        <div className="flex items-center justify-center bg-muted rounded-md px-2 py-1 text-xs text-muted-foreground">
          +{remainingCount} more
        </div>
      )}
    </div>
  );
};

const formatDate = (dateString: string) => {
  if (!dateString) return "-";
  return new Date(dateString).toLocaleDateString("en-US", {
    year: "numeric",
    month: "short",
    day: "numeric",
  });
};

